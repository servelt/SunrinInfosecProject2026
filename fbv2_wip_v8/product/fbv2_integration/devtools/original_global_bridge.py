"""Opt-in FBv2 Direction Seed handoff to the existing guarded Global campaign.

The caller must supply a product-issued official V2 qualification through an
existing ``DevGlobalCampaign``. This adapter stages FBv2's generated bytes;
``DevGlobalCampaign`` owns physical execution, observation consumption,
independent replay, and the unchanged product Gate. It never starts original
Docker ``FuzzerInstance`` or labels a crash VERIFIED on its own.

This is a development bridge, not an authorized Blind runner. SP targeted
fuzzing remains unsupported here and fails closed.
"""

from __future__ import annotations

import asyncio
from dataclasses import dataclass
import hashlib
import json
import os
from pathlib import Path
import re
import secrets
import stat
from typing import Any


_SHA256 = re.compile(r"[0-9a-f]{64}\Z")
_DIRECTION_ID = re.compile(r"[A-Za-z0-9_-]+\Z")
MAX_SEED_BYTES = 2_097_152  # Same admission ceiling as DevGlobalCampaign.
MAX_STAGED_SEEDS = 128
MAX_STAGED_SEED_BYTES = 16 * 1024 * 1024


def _settled_crash_observation(result: dict[str, Any]) -> bool:
    """A retained crash is terminal for the process, not a completed fuzz budget."""
    return (result.get("status") == "CRASH_OBSERVED_INCOMPLETE" and
            result.get("cleanup_complete") is True and
            type(result.get("observed_crash_count")) is int and
            result["observed_crash_count"] > 0 and
            type(result.get("consumer_rows")) is list)


@dataclass(frozen=True)
class PinnedDirectionSeed:
    direction_id: str
    path: Path
    sha256: str


def _sha256(path: Path) -> str:
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def _plain_file(path: Path) -> bool:
    return (not path.is_symlink() and path.is_file() and
            stat.S_ISREG(path.stat(follow_symlinks=False).st_mode))


def export_completed_direction_plan(
    *, repos: Any, task_id: str, fuzzer: str, agent_id: str,
    agent_result: dict[str, Any], agent_final: bool, output_path: Path,
) -> tuple[Path, str]:
    """Pin only Directions created by one completed original Agent call.

    Direction rows are still ``pending`` for SP analysis; ``COMPLETED`` here
    means only that the Direction planning call ended conclusively. A stale
    pending row, mismatched Agent owner, missing tool-result ID, or changed
    plan path refuses export. No Direction is inferred from model prose.
    """
    if (agent_final is not True or type(agent_result) is not dict or
            agent_result.get("success") is not True or
            not all(isinstance(value, str) and _DIRECTION_ID.fullmatch(value)
                    for value in (task_id, fuzzer, agent_id))):
        raise ValueError("original Direction Agent did not finish conclusively")
    ids = agent_result.get("direction_ids")
    count = agent_result.get("directions_created")
    if (type(ids) is not list or not ids or
            any(type(value) is not str or not _DIRECTION_ID.fullmatch(value)
                for value in ids) or len(set(ids)) != len(ids) or
            type(count) is not int or count != len(ids)):
        raise ValueError("Direction tool-result IDs are missing or duplicated")
    pending = repos.directions.find_pending(task_id, fuzzer)
    if (type(pending) is not list or len(pending) != len(ids) or
            {getattr(row, "direction_id", None) for row in pending} != set(ids)):
        raise ValueError("pending Directions differ from this Agent call")
    for row in pending:
        if (getattr(row, "task_id", None) != task_id or
                getattr(row, "fuzzer", None) != fuzzer or
                getattr(row, "created_by_agent_id", None) != agent_id or
                getattr(row, "status", None) != "pending"):
            raise ValueError("Direction owner, task, fuzzer, or state changed")
    output = Path(output_path)
    if (not output.is_absolute() or output != output.resolve() or
            output.exists() or output.is_symlink() or
            any(parent.is_symlink() for parent in output.parents) or
            not output.parent.is_dir()):
        raise ValueError("Direction plan output must be a new plain absolute file")
    payload = {
        "kind": "FBV2_DEV_DIRECTION_PLAN_V1", "status": "COMPLETED",
        "task_id": task_id, "fuzzer": fuzzer,
        "created_by_agent_id": agent_id,
        "direction_ids": ids, "direction_count": len(ids),
        "source": "ORIGINAL_FBV2_AGENT_TOOL_RESULTS",
    }
    content = (json.dumps(payload, sort_keys=True, separators=(",", ":")) +
               "\n").encode("utf-8")
    temporary = output.with_name(output.name + "." + secrets.token_hex(12) + ".tmp")
    fd = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW,
                 0o600)
    try:
        with os.fdopen(fd, "wb") as stream:
            stream.write(content)
            stream.flush()
            os.fsync(stream.fileno())
        # Link gives an atomic no-overwrite publish. Replacing an older plan
        # would make its already-staged seeds ambiguous.
        os.link(temporary, output, follow_symlinks=False)
        temporary.unlink()
        parent_fd = os.open(output.parent, os.O_RDONLY | os.O_DIRECTORY)
        try:
            os.fsync(parent_fd)
        finally:
            os.close(parent_fd)
    finally:
        temporary.unlink(missing_ok=True)
    return output, hashlib.sha256(content).hexdigest()


class OriginalGlobalBridge:
    """The narrow Global subset of original ``FuzzerManager``'s API.

    The original Fullscan calls ``add_direction_seed`` during SeedAgent tool
    execution and ``start_global_fuzzer`` before SP batches. The caller must
    call ``stop_global_fuzzer`` once at task settlement, or ``abort`` on an
    incomplete run. A result with cleanup failure remains incomplete.
    """

    def __init__(self, *, campaign: Any, direction_plan_path: Path,
                 direction_plan_sha256: str, seed_spool: Path,
                 expected_binary_sha256: str, model_gate: Any = None) -> None:
        if (not _SHA256.fullmatch(direction_plan_sha256) or
                not _SHA256.fullmatch(expected_binary_sha256)):
            raise ValueError("missing pinned Direction plan or binary SHA-256")
        plan = Path(direction_plan_path)
        if (not plan.is_absolute() or plan != plan.resolve() or
                not _plain_file(plan) or _sha256(plan) != direction_plan_sha256):
            raise ValueError("Direction plan identity changed")
        try:
            payload = json.loads(plan.read_text(encoding="utf-8"))
        except (OSError, UnicodeError, ValueError) as exc:
            raise ValueError("Direction plan is unreadable") from exc
        ids = payload.get("direction_ids") if isinstance(payload, dict) else None
        if (not isinstance(payload, dict) or payload.get("status") != "COMPLETED" or
                not isinstance(ids, list) or not ids or
                any(not isinstance(value, str) or
                    not _DIRECTION_ID.fullmatch(value) for value in ids) or
                len(ids) != len(set(ids))):
            raise ValueError("Direction plan is not a completed pinned plan")
        qualification = getattr(campaign, "q", None)
        if (qualification is None or
                getattr(qualification, "product_issued", None) is not True or
                getattr(qualification, "contract_kind", None) !=
                "OFFICIAL_OSS_FUZZ_UPSTREAM_HARNESS_V2" or
                getattr(qualification, "binary_sha256", None) !=
                expected_binary_sha256 or
                not callable(getattr(campaign, "_authority_ok", None)) or
                not campaign._authority_ok()):
            raise ValueError("official V2 binary/Harness authority is unavailable")
        if (not callable(getattr(campaign, "stage_direction_seeds", None)) or
                not callable(getattr(campaign, "start", None)) or
                not callable(getattr(campaign, "finish", None)) or
                not callable(getattr(campaign, "abort", None))):
            raise TypeError("existing guarded Global campaign is required")
        if getattr(campaign, "require_accounted_consumer", None) is not True:
            raise ValueError("accounted Global Crash consumer is required")
        if (type(getattr(campaign, "global_seconds", None)) is not int or
                campaign.global_seconds < 1 or
                getattr(campaign, "global_wall_reservation_seconds", 0) <
                campaign.global_seconds):
            raise ValueError("bounded physical Global budget is required")
        spool = Path(seed_spool)
        if (not spool.is_absolute() or spool != spool.resolve() or
                spool.is_symlink() or any(parent.is_symlink()
                                          for parent in spool.parents) or
                not spool.parent.is_dir()):
            raise ValueError("seed spool must be a new plain absolute directory")
        spool.mkdir(mode=0o700, exist_ok=False)

        self.campaign = campaign
        self.model_gate = model_gate
        self.plan_path = plan
        self.plan_sha256 = direction_plan_sha256
        self.binary_sha256 = expected_binary_sha256
        self.spool = spool
        self.direction_ids = frozenset(ids)
        self.direction_seeds: list[PinnedDirectionSeed] = []
        self._seed_keys: dict[tuple[str, str], Path] = {}
        self._staged_seed_bytes = 0
        self._start_attempted = False
        self._started = False
        self.final_result: dict[str, Any] | None = None
        self._settlement_task: asyncio.Task | None = None
        self._settlement_kind: str | None = None

    @property
    def final_result(self) -> dict[str, Any] | None:
        result = self._final_result
        if isinstance(result, dict) and "durable_global_charge" in result:
            # The product-backed campaign may complete Global before a later
            # PoV or Crash-consumer AUX turn stops the shared process ledger.
            # Never serve this bridge's cached RAN without checking the
            # underlying durable Global row and current stop state again.
            current = self.campaign.final_result
            if (not isinstance(current, dict) or
                    current.get("durable_global_charge") !=
                    result["durable_global_charge"] or
                    current.get("status") != result.get("status")):
                raise RuntimeError("cached Global result differs from durable account")
        elif isinstance(result, dict) and result.get("status") == "SKIPPED_NO_SEED":
            current = self.campaign.final_result
            if current != result:
                raise RuntimeError("cached no-seed Global result differs from durable account")
        return result

    @final_result.setter
    def final_result(self, result: dict[str, Any] | None) -> None:
        self._final_result = result

    async def _settle_campaign(self, kind: str) -> dict[str, Any]:
        """Serialize physical finish/abort even across caller cancellation.

        ``asyncio.to_thread`` keeps running after its awaiting coroutine is
        cancelled. Shielding one owned task and joining it before another
        settlement prevents concurrent reads/closes of the same guard fd and
        double charging the product's physical budget.
        """
        if self.final_result is not None:
            return self.final_result
        task = self._settlement_task
        if task is not None and task.done() and task.exception() is not None:
            if kind != "abort" or self._settlement_kind != "finish":
                raise RuntimeError("Global settlement failed and cannot be retried")
            # The failed finish thread has fully ended. One abort can now
            # safely reclaim a process that may still be running.
            task = None
        if task is None:
            self._settlement_kind = kind
            task = asyncio.create_task(asyncio.to_thread(getattr(self.campaign, kind)))
            self._settlement_task = task
        try:
            result = await asyncio.shield(task)
        except asyncio.CancelledError:
            # The thread itself was not cancelled. Preserve its result before
            # propagating cancellation so the caller's abort joins this same
            # settlement rather than racing it.
            result = await asyncio.shield(task)
            if type(result) is not dict:
                raise RuntimeError("Global settlement returned no receipt")
            self.final_result = result
            self._started = False
            raise
        if type(result) is not dict:
            raise RuntimeError("Global settlement returned no receipt")
        self.final_result = result
        self._started = False
        return result

    def _authority_ok(self) -> bool:
        return (self.campaign._authority_ok() and
                getattr(self.campaign.q, "binary_sha256", None) ==
                self.binary_sha256 and _plain_file(self.plan_path) and
                _sha256(self.plan_path) == self.plan_sha256)

    def add_direction_seed(self, seed: bytes, direction_id: str) -> Path:
        if self._start_attempted:
            raise RuntimeError("Direction corpus is sealed after Global start attempt")
        if (not isinstance(seed, bytes) or not seed or
                len(seed) > MAX_SEED_BYTES or
                not isinstance(direction_id, str) or
                direction_id not in self.direction_ids or
                not _DIRECTION_ID.fullmatch(direction_id) or
                not self._authority_ok()):
            raise ValueError("untrusted Direction seed or changed authority")
        digest = hashlib.sha256(seed).hexdigest()
        key = (direction_id, digest)
        previous = self._seed_keys.get(key)
        if previous is not None:
            if not _plain_file(previous) or _sha256(previous) != digest:
                raise ValueError("staged Direction seed changed")
            return previous
        if (len(self.direction_seeds) >= MAX_STAGED_SEEDS or
                self._staged_seed_bytes + len(seed) > MAX_STAGED_SEED_BYTES):
            raise ValueError("bounded Direction seed corpus exhausted")
        path = self.spool / f"direction_{direction_id}_{digest}"
        if path.exists() or path.is_symlink():
            raise FileExistsError("Direction seed path already exists")
        fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW,
                     0o600)
        try:
            with os.fdopen(fd, "wb") as stream:
                stream.write(seed)
                stream.flush()
                os.fsync(stream.fileno())
            parent_fd = os.open(self.spool, os.O_RDONLY | os.O_DIRECTORY)
            try:
                os.fsync(parent_fd)
            finally:
                os.close(parent_fd)
        except BaseException:
            path.unlink(missing_ok=True)
            raise
        self._seed_keys[key] = path
        self._staged_seed_bytes += len(seed)
        self.direction_seeds.append(PinnedDirectionSeed(direction_id, path, digest))
        return path

    async def start_global_fuzzer(self, initial_seeds: list[bytes] | None = None) -> bool:
        if initial_seeds is not None:
            raise ValueError("untracked initial seeds are not admitted")
        if self._start_attempted:
            raise RuntimeError("Global start cannot be retried")
        self._start_attempted = True
        if not self.direction_seeds:
            return False
        if (not self._authority_ok() or any(
                not _plain_file(item.path) or
                item.path.stat().st_size > MAX_SEED_BYTES or
                _sha256(item.path) != item.sha256
                for item in self.direction_seeds)):
            raise ValueError("Direction seed or pinned authority changed")
        # The existing product campaign rechecks authority, stages private
        # corpus bytes, reserves physical wall, and launches its guarded worker.
        self.campaign.stage_direction_seeds(
            self.plan_path, self.plan_sha256, list(self.direction_seeds))
        try:
            status = self.campaign.start()
        except BaseException as original:
            # DevGlobalCampaign may have launched the guarded process before
            # its start receipt failed. Never leave it running after refusal.
            if getattr(self.campaign, "process", None) is not None:
                try:
                    self.final_result = await self._settle_campaign("abort")
                except BaseException as cleanup:
                    original.add_note(
                        f"Global abort after start failure failed: {type(cleanup).__name__}")
            raise
        if status != "ACTIVE" and getattr(self.campaign, "process", None) is not None:
            self.final_result = await self._settle_campaign("abort")
            if self.final_result.get("cleanup_complete") is not True:
                raise RuntimeError("Global Fuzzer process cleanup is incomplete")
        self._started = status == "ACTIVE"
        return self._started

    def record_clean_no_seed(self, *, seed_results: list[dict[str, Any]],
                             expected_direction_ids: list[str],
                             model_gate: Any) -> dict[str, Any]:
        """Record only completed zero-Seed agents and a physically absent Global."""
        if (model_gate is None or model_gate is not self.model_gate or
                self._start_attempted or self._started or
                self.final_result is not None or
                self.direction_seeds or any(self.spool.iterdir()) or
                not self._authority_ok() or
                type(seed_results) is not list or
                type(expected_direction_ids) is not list or
                not expected_direction_ids or
                len(seed_results) != len(expected_direction_ids) or
                len(set(expected_direction_ids)) != len(expected_direction_ids) or
                not set(expected_direction_ids).issubset(self.direction_ids)):
            raise ValueError("clean no-seed Global preconditions are absent")
        observed_ids = []
        for item in seed_results:
            if type(item) is not dict or item.get("error") is not None:
                raise ValueError("Seed Agent failure cannot become clean skip")
            direction = item.get("direction")
            result = item.get("result")
            if (direction is None or type(result) is not dict or
                    result.get("success") is not True or
                    type(result.get("seeds_generated")) is not int or
                    result["seeds_generated"] != 0 or
                    type(result.get("seed_tool_failures")) is not int or
                    result["seed_tool_failures"] != 0 or
                    result.get("fatal_seed_cleanup") is not False or
                    result.get("direction_id") != direction.direction_id):
                raise ValueError("Seed Agent result is not a completed zero")
            observed_ids.append(direction.direction_id)
        if observed_ids != expected_direction_ids:
            raise ValueError("zero-Seed results do not match planned Directions")
        if not callable(getattr(self.campaign, "record_clean_no_seed", None)):
            raise RuntimeError("durable no-seed Global settlement is unavailable")
        self._start_attempted = True
        result = self.campaign.record_clean_no_seed(
            plan_path=self.plan_path, plan_sha256=self.plan_sha256,
            direction_ids=expected_direction_ids, model_gate=model_gate)
        if result.get("status") != "SKIPPED_NO_SEED":
            raise RuntimeError("no-seed Global settlement did not complete")
        self.final_result = result
        return self.final_result

    async def stop_global_fuzzer(self) -> dict[str, Any] | None:
        if not self._started:
            if (self.final_result is not None and
                    self.final_result.get("cleanup_complete") is not True):
                raise RuntimeError("Global Fuzzer process cleanup is incomplete")
            if (self.final_result is not None and
                    self.final_result.get("status") not in {"RAN", "SKIPPED_NO_SEED"}
                    and not _settled_crash_observation(self.final_result)):
                raise RuntimeError(
                    "Global Fuzzer result is incomplete: "
                    f"{self.final_result.get('status')}")
            return self.final_result
        if self.final_result is None:
            self.final_result = await self._settle_campaign("finish")
        if self.final_result.get("cleanup_complete") is not True:
            raise RuntimeError("Global Fuzzer process cleanup is incomplete")
        if (self.final_result.get("status") != "RAN" and
                not _settled_crash_observation(self.final_result)):
            raise RuntimeError(
                "Global Fuzzer result is incomplete: "
                f"{self.final_result.get('status')}")
        return self.final_result

    async def abort(self) -> dict[str, Any] | None:
        if (not self._started and self.final_result is None and
                getattr(self.campaign, "process", None) is not None):
            # A start receipt can fail after launch. Reconcile the physical
            # process even when ACTIVE was never observed by this adapter.
            self.final_result = await self._settle_campaign("abort")
        if not self._started:
            if (self.final_result is not None and
                    self.final_result.get("cleanup_complete") is not True):
                raise RuntimeError("Global Fuzzer process cleanup is incomplete")
            return self.final_result
        if self.final_result is None:
            self.final_result = await self._settle_campaign("abort")
        if self.final_result.get("cleanup_complete") is not True:
            raise RuntimeError("Global Fuzzer process cleanup is incomplete")
        return self.final_result

    async def shutdown_sp_fuzzers_only(self) -> None:
        """Match WorkerExecutor.close; this bridge never starts an SP Fuzzer."""
        return None

    async def shutdown(self) -> None:
        """Match Dispatcher shutdown and settle the existing Global owner."""
        await self.stop_global_fuzzer()

    def get_status(self) -> dict[str, Any]:
        return {"kind": "FBV2_PRODUCT_GLOBAL_DEV_BRIDGE",
                "direction_seed_count": len(self.direction_seeds),
                "start_attempted": self._start_attempted,
                "active": self._started,
                "final_result": self.final_result}

    def add_fp_seed(self, *_args: Any, **_kwargs: Any) -> None:
        raise RuntimeError("SP/FP seed routing is not integrated in this Global bridge")

    async def start_sp_fuzzer(self, *_args: Any, **_kwargs: Any) -> bool:
        raise RuntimeError("SP targeted Fuzzer is not integrated in this Global bridge")

    async def stop_sp_fuzzer(self, *_args: Any, **_kwargs: Any) -> None:
        raise RuntimeError("SP targeted Fuzzer is not integrated in this Global bridge")

    def add_pov_blob(self, *_args: Any, **_kwargs: Any) -> None:
        raise RuntimeError("SP PoV corpus is not integrated in this Global bridge")
